"""HTML and Markdown renderers for security reports."""

from __future__ import annotations

import html
from typing import Any


def escape_html(value: Any) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def _severity_label(value: str | None) -> str:
    text = str(value or "low")
    return text[:1].upper() + text[1:]


def _evidence_lines(finding: dict[str, Any]) -> list[str]:
    lines: list[str] = []
    for item in finding.get("evidence_locations") or []:
        kind = item.get("kind") or "evidence"
        loc = item.get("location") or {}
        snippet = loc.get("snippet") or finding.get("snippet") or ""
        line = loc.get("line")
        label = str(kind).replace("_", " ").title()
        if snippet:
            where = f" (line {line})" if line is not None else ""
            lines.append(f"{label}{where}: {snippet}")
        else:
            lines.append(label)
    if not lines and finding.get("snippet"):
        lines.append(str(finding["snippet"]))
    return lines


def render_markdown_report(report: dict[str, Any]) -> str:
    summary = report.get("summary") or {}
    exec_summary = report.get("executive_summary") or {}
    lines: list[str] = [
        f"# Security Report: {report.get('project_name', 'project')}",
        "",
        "## Scan Summary",
        "",
        f"- **Project:** {report.get('project_name')}",
        f"- **Path:** `{report.get('project_path')}`",
        f"- **Scan date:** {report.get('scanned_at')}",
        f"- **Files scanned:** {report.get('files_scanned', 0)}",
        f"- **Scan duration:** {report.get('duration_seconds', 0)}s",
        f"- **Security score:** {report.get('security_score', 0)} / 100",
        f"- **Total findings:** {summary.get('total_findings', 0)}",
        f"- **High:** {summary.get('high', 0)}",
        f"- **Medium:** {summary.get('medium', 0)}",
        f"- **Low:** {summary.get('low', 0)}",
        "",
        "## Top Risk Categories",
        "",
    ]

    categories = report.get("top_risk_categories") or []
    if not categories:
        lines.append("_No risk categories — no findings._")
    else:
        lines.append("| Category | Count | Highest Severity |")
        lines.append("| --- | ---: | --- |")
        for item in categories:
            lines.append(
                f"| {item.get('display_name')} | {item.get('count')} | "
                f"{_severity_label(item.get('highest_severity'))} |"
            )

    lines.extend(
        [
            "",
            "## Executive Summary",
            "",
            "### Overall security posture",
            "",
            exec_summary.get("overall_posture", ""),
            "",
            "### Highest-risk vulnerability type",
            "",
            exec_summary.get("highest_risk_type", ""),
            "",
            "### Highest-priority files",
            "",
            exec_summary.get("highest_priority_files", ""),
            "",
            "### Recommended remediation order",
            "",
            exec_summary.get("recommended_remediation_order", ""),
            "",
        ]
    )

    ai_summary = report.get("ai_executive_summary")
    if ai_summary:
        lines.extend(
            [
                "## AI Executive Summary",
                "",
                "_AI-generated. Does not classify findings or override the deterministic engine._",
                "",
                ai_summary,
                "",
            ]
        )

    lines.extend(["## Findings", ""])
    findings = report.get("findings") or []
    if not findings:
        lines.append("_No findings detected._")
    else:
        for index, finding in enumerate(findings, start=1):
            lines.extend(_markdown_finding_card(index, finding))

    lines.extend(
        [
            "",
            "---",
            "",
            "_Generated by AI Security Assistant. Deterministic engine is the source of truth._",
            "",
        ]
    )
    return "\n".join(lines)


def _markdown_finding_card(index: int, finding: dict[str, Any]) -> list[str]:
    severity = _severity_label(finding.get("confidence"))
    file_ref = finding.get("file") or "unknown"
    line = finding.get("line")
    location = f"{file_ref}:{line}" if line is not None else file_ref
    card = [
        f"### {index}. {finding.get('display_name') or finding.get('issue_type')}",
        "",
        f"- **Issue type:** `{finding.get('issue_type')}`",
        f"- **Severity / Confidence:** {severity}",
        f"- **Location:** `{location}`",
        "",
        "**Evidence**",
        "",
    ]
    evidence = _evidence_lines(finding)
    if evidence:
        for item in evidence:
            card.append(f"- `{item}`")
    else:
        card.append("- _No evidence locations provided._")

    card.extend(
        [
            "",
            "**Why it was flagged**",
            "",
            finding.get("missing_control")
            or "Potential security issue indicated by the deterministic analyzer.",
            "",
            "**Impact**",
            "",
            finding.get("impact")
            or "Impact depends on whether untrusted callers can trigger this behavior.",
            "",
            "**Recommended remediation**",
            "",
        ]
    )
    recommendations = list(finding.get("recommendations") or [])
    if recommendations:
        for item in recommendations[:5]:
            card.append(f"- {item}")
    else:
        card.append("- Review and apply the safest available control for this finding.")

    suggestion = finding.get("ai_fix_suggestion")
    if isinstance(suggestion, dict) and suggestion.get("replacement_code"):
        card.extend(
            [
                "",
                "**AI Fix Suggestion**",
                "",
                "_AI-generated suggestion. Review before applying. Not guaranteed secure._",
                "",
                suggestion.get("summary") or "",
                "",
                "```python",
                str(suggestion.get("replacement_code")),
                "```",
                "",
                suggestion.get("explanation") or "",
                "",
            ]
        )

    card.append("")
    return card


