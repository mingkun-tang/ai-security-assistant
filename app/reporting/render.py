def _html_finding_card(index: int, finding: dict[str, Any]) -> str:
    severity = str(finding.get("confidence") or "low")
    file_ref = finding.get("file") or "unknown"
    line = finding.get("line")
    location = f"{file_ref}:{line}" if line is not None else str(file_ref)
    evidence = _evidence_lines(finding)
    evidence_html = (
        "<ul>"
        + "".join(f"<li><code>{escape_html(item)}</code></li>" for item in evidence)
        + "</ul>"
        if evidence
        else "<p class='muted'>No evidence locations provided.</p>"
    )
    recommendations = list(finding.get("recommendations") or [])
    rec_html = (
        "<ul>"
        + "".join(f"<li>{escape_html(item)}</li>" for item in recommendations[:5])
        + "</ul>"
        if recommendations
        else "<p>Review and apply the safest available control for this finding.</p>"
    )

    suggestion = finding.get("ai_fix_suggestion")
    suggestion_html = ""
    if isinstance(suggestion, dict) and suggestion.get("replacement_code"):
        suggestion_html = f"""
        <div class="ai-fix">
          <h3>AI Fix Suggestion</h3>
          <p class="disclaimer">AI-generated suggestion. Review before applying. Not guaranteed secure.</p>
          <p>{escape_html(suggestion.get('summary'))}</p>
          <pre>{escape_html(suggestion.get('replacement_code'))}</pre>
          <p>{escape_html(suggestion.get('explanation'))}</p>
        </div>
        """

    return f"""
    <article class="finding" id="finding-{index}">
      <h3>{index}. {escape_html(finding.get('display_name') or finding.get('issue_type'))}
        <span class="badge {escape_html(severity)}">{escape_html(_severity_label(severity))}</span>
      </h3>
      <p><strong>Issue type:</strong> <code>{escape_html(finding.get('issue_type'))}</code></p>
      <p><strong>Location:</strong> <code>{escape_html(location)}</code></p>
      <h3>Evidence</h3>
      {evidence_html}
      <h3>Why it was flagged</h3>
      <p>{escape_html(finding.get('missing_control') or 'Potential security issue indicated by the deterministic analyzer.')}</p>
      <h3>Impact</h3>
      <p>{escape_html(finding.get('impact') or 'Impact depends on whether untrusted callers can trigger this behavior.')}</p>
      <h3>Recommended remediation</h3>
      {rec_html}
      {suggestion_html}
    </article>
    """
